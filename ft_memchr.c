#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	const unsigned char	*str;
	size_t				i;

	str = (const unsigned char *)s;
	i = 0;
	while (i < n)
	{
		if (str[i] == (const unsigned char)c)
			return ((void *)&str[i]);
		i++;
	}
	return (NULL);
}
